//! `manifest`: list test files by name, real format, size and checksum, so the
//! private corpus can be described in the repository without its contents.

use std::path::{Path, PathBuf};
use std::process::ExitCode;

pub(crate) fn run(args: &[String]) -> ExitCode {
    if args.is_empty() {
        return crate::usage_error("manifest needs at least one folder");
    }
    let mut ok = true;
    println!("# Generated by `oxiguitar-cli manifest`. Formats come from file contents (FMT-6).");
    for dir in args {
        let mut files = Vec::new();
        if let Err(e) = collect(Path::new(dir), &mut files) {
            eprintln!("{dir}: {e}");
            ok = false;
            continue;
        }
        files.sort();
        let set = Path::new(dir)
            .file_name()
            .map_or_else(|| dir.clone(), |n| n.to_string_lossy().into_owned());
        for path in files {
            let data = match std::fs::read(&path) {
                Ok(d) => d,
                Err(e) => {
                    eprintln!("{}: {e}", path.display());
                    ok = false;
                    continue;
                }
            };
            let name = path
                .strip_prefix(dir)
                .unwrap_or(&path)
                .to_string_lossy()
                .replace('\\', "/");
            let format = oxiguitar_formats::detect(&data)
                .map_or_else(|| "unknown".to_owned(), |f| f.describe());
            println!();
            println!("[[file]]");
            println!("set = {}", toml_str(&set));
            println!("name = {}", toml_str(&name));
            println!("format = {}", toml_str(&format));
            println!("bytes = {}", data.len());
            println!("sha256 = \"{}\"", crate::sha256::hex_digest(&data));
        }
    }
    if ok {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    }
}

fn collect(dir: &Path, out: &mut Vec<PathBuf>) -> std::io::Result<()> {
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            collect(&path, out)?;
        } else {
            out.push(path);
        }
    }
    Ok(())
}

fn toml_str(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => out.push_str(&format!("\\u{:04X}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
