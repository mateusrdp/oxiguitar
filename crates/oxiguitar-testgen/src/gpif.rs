//! Writes a [`Song`] as Guitar Pro 7 GPIF XML and packs it as a .gp file.
//!
//! Only what the generated songs use is written, in the shape Guitar Pro 7
//! saves it. This is not the M2 writer: it never sees a real score.

use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;
use std::io::Write as _;

use crate::song::{At, Beat, Dur, Fx, Kind, Song};

/// The song as a Guitar Pro 7 file (a ZIP archive).
pub fn to_gp(song: &Song) -> Vec<u8> {
    pack(&to_gpif(song), &part_configuration(song))
}

/// A .gp archive around a score.gpif and its PartConfiguration.
pub fn pack(gpif: &str, part_configuration: &[u8]) -> Vec<u8> {
    let mut zip = zip::ZipWriter::new(std::io::Cursor::new(Vec::new()));
    // A fixed date keeps the archive the same from run to run.
    let opts = zip::write::SimpleFileOptions::default()
        .compression_method(zip::CompressionMethod::Deflated)
        .last_modified_time(zip::DateTime::default());
    let mut put = |name: &str, data: &[u8]| {
        zip.start_file(name, opts).expect("in-memory zip");
        zip.write_all(data).expect("in-memory zip");
    };
    put("VERSION", b"7.0");
    put("Content/score.gpif", gpif.as_bytes());
    put("Content/PartConfiguration", part_configuration);
    zip.finish().expect("in-memory zip").into_inner()
}

/// PartConfiguration: one score view, one notation flag per track.
pub fn part_configuration(song: &Song) -> Vec<u8> {
    let mut v = Vec::new();
    v.extend_from_slice(&1u32.to_be_bytes());
    v.push(0);
    v.extend_from_slice(&(song.tracks.len() as u32).to_be_bytes());
    v.extend(song.tracks.iter().map(|t| t.notation));
    v
}

fn cdata(x: &mut String, tag: &str, text: &str) {
    let _ = writeln!(x, "<{tag}><![CDATA[{text}]]></{tag}>");
}

/// Ids handed out as elements are written.
#[derive(Default)]
struct Ids {
    bars: Vec<String>,
    voices: Vec<String>,
    beats: Vec<String>,
    notes: Vec<String>,
    rhythms: BTreeMap<Dur, usize>,
}

/// The song's score.gpif.
pub fn to_gpif(song: &Song) -> String {
    let mut x = String::new();
    x.push_str("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<GPIF>\n");
    x.push_str("<GPVersion>7</GPVersion>\n<GPRevision required=\"12021\" recommended=\"12023\">12025</GPRevision>\n");
    x.push_str("<Encoding><EncodingDescription>GP7</EncodingDescription></Encoding>\n<Score>\n");
    for (tag, text) in [
        ("Title", &song.title),
        ("SubTitle", &song.subtitle),
        ("Artist", &song.artist),
        ("Album", &song.album),
        ("Words", &song.words),
        ("Music", &song.music),
        ("WordsAndMusic", &String::new()),
        ("Copyright", &song.copyright),
        ("Tabber", &song.tabber),
        ("Instructions", &String::new()),
        ("Notices", &"Generated by oxiguitar-testgen".to_owned()),
    ] {
        cdata(&mut x, tag, text);
    }
    x.push_str("</Score>\n<MasterTrack>\n");
    let ids: Vec<String> = (0..song.tracks.len()).map(|i| i.to_string()).collect();
    let _ = writeln!(x, "<Tracks>{}</Tracks>\n<Automations>", ids.join(" "));
    let _ = writeln!(
        x,
        "<Automation><Type>Tempo</Type><Linear>false</Linear><Bar>0</Bar><Position>0</Position>\
         <Visible>true</Visible><Value>{} 2</Value><Text>{}</Text></Automation>",
        song.tempo, song.tempo_label
    );
    for (bar, position, bpm) in &song.tempo_changes {
        let _ = writeln!(
            x,
            "<Automation><Type>Tempo</Type><Linear>false</Linear><Bar>{bar}</Bar><Position>{position}</Position>\
             <Visible>true</Visible><Value>{bpm} 2</Value></Automation>"
        );
    }
    x.push_str("</Automations>\n</MasterTrack>\n<Tracks>\n");
    for (ti, track) in song.tracks.iter().enumerate() {
        write_track(&mut x, ti, track);
    }
    x.push_str("</Tracks>\n");

    // Bars, voices, beats and notes, numbered as they are met.
    let mut id = Ids::default();
    let mut master_bar_ids: Vec<Vec<usize>> = vec![Vec::new(); song.bars.len()];
    for track in &song.tracks {
        let origins = tie_origins(track);
        for (bi, ids) in master_bar_ids.iter_mut().enumerate() {
            let mut voice_ids = Vec::new();
            for (vi, voice) in track.voices.iter().enumerate() {
                match voice.get(bi) {
                    Some(beats) if !beats.is_empty() => {
                        let mut beat_ids = Vec::new();
                        for (ki, beat) in beats.iter().enumerate() {
                            beat_ids.push(write_beat(&mut id, track, beat, |ni| {
                                origins.contains(&(vi, bi, ki, ni))
                            }));
                        }
                        voice_ids.push(id.voices.len().to_string());
                        id.voices.push(format!(
                            "<Voice id=\"{}\"><Beats>{}</Beats></Voice>",
                            id.voices.len(),
                            beat_ids.join(" ")
                        ));
                    }
                    _ => voice_ids.push("-1".to_owned()),
                }
            }
            voice_ids.resize(4, "-1".to_owned());
            if voice_ids[0] == "-1" {
                // Every bar has a first voice, even if empty.
                voice_ids[0] = id.voices.len().to_string();
                id.voices.push(format!(
                    "<Voice id=\"{}\"><Beats></Beats></Voice>",
                    id.voices.len()
                ));
            }
            let clef = match &track.kind {
                Kind::Drums => "Neutral",
                Kind::Fretted { bass_clef, .. } | Kind::Pitched { bass_clef, .. } => {
                    if *bass_clef {
                        "F4"
                    } else {
                        "G2"
                    }
                }
            };
            ids.push(id.bars.len());
            id.bars.push(format!(
                "<Bar id=\"{}\"><Clef>{clef}</Clef><Voices>{}</Voices></Bar>",
                id.bars.len(),
                voice_ids.join(" ")
            ));
        }
    }

    x.push_str("<MasterBars>\n");
    for (mb, ids) in song.bars.iter().zip(&master_bar_ids) {
        let _ = write!(
            x,
            "<MasterBar><Key><AccidentalCount>{}</AccidentalCount><Mode>{}</Mode></Key><Time>{}/{}</Time>",
            mb.key,
            if mb.minor { "Minor" } else { "Major" },
            mb.time.0,
            mb.time.1
        );
        let list: Vec<String> = ids.iter().map(ToString::to_string).collect();
        let _ = write!(x, "<Bars>{}</Bars>", list.join(" "));
        if mb.repeat_start || mb.repeat_end.is_some() {
            let _ = write!(
                x,
                "<Repeat start=\"{}\" end=\"{}\" count=\"{}\"/>",
                mb.repeat_start,
                mb.repeat_end.is_some(),
                mb.repeat_end.unwrap_or(0)
            );
        }
        if !mb.endings.is_empty() {
            let e: Vec<String> = mb.endings.iter().map(ToString::to_string).collect();
            let _ = write!(x, "<AlternateEndings>{}</AlternateEndings>", e.join(" "));
        }
        if let Some((letter, text)) = &mb.section {
            let _ = write!(
                x,
                "<Section><Letter><![CDATA[{letter}]]></Letter><Text><![CDATA[{text}]]></Text></Section>"
            );
        }
        if mb.double_bar {
            x.push_str("<DoubleBar/>");
        }
        if let Some(feel) = mb.triplet_feel {
            let _ = write!(x, "<TripletFeel>{feel}</TripletFeel>");
        }
        if !mb.directions.is_empty() {
            x.push_str("<Directions>");
            for d in &mb.directions {
                let tag = if matches!(*d, "Segno" | "SegnoSegno" | "Coda" | "DoubleCoda" | "Fine") {
                    "Target"
                } else {
                    "Jump"
                };
                let _ = write!(x, "<{tag}>{d}</{tag}>");
            }
            x.push_str("</Directions>");
        }
        x.push_str("</MasterBar>\n");
    }
    x.push_str("</MasterBars>\n<Bars>\n");
    for b in &id.bars {
        let _ = writeln!(x, "{b}");
    }
    x.push_str("</Bars>\n<Voices>\n");
    for v in &id.voices {
        let _ = writeln!(x, "{v}");
    }
    x.push_str("</Voices>\n<Beats>\n");
    for b in &id.beats {
        let _ = writeln!(x, "{b}");
    }
    x.push_str("</Beats>\n<Notes>\n");
    for n in &id.notes {
        let _ = writeln!(x, "{n}");
    }
    x.push_str("</Notes>\n<Rhythms>\n");
    let mut rhythms: Vec<(&Dur, &usize)> = id.rhythms.iter().collect();
    rhythms.sort_by_key(|(_, i)| **i);
    for (d, i) in rhythms {
        let value = match d.value {
            1 => "Whole",
            2 => "Half",
            4 => "Quarter",
            8 => "Eighth",
            16 => "16th",
            32 => "32nd",
            _ => "64th",
        };
        let _ = write!(x, "<Rhythm id=\"{i}\"><NoteValue>{value}</NoteValue>");
        if d.dots > 0 {
            let _ = write!(x, "<AugmentationDot count=\"{}\"/>", d.dots);
        }
        if let Some((n, m)) = d.tuplet {
            let _ = write!(x, "<PrimaryTuplet num=\"{n}\" den=\"{m}\"/>");
        }
        x.push_str("</Rhythm>\n");
    }
    x.push_str("</Rhythms>\n</GPIF>\n");
    x
}

fn write_track(x: &mut String, ti: usize, track: &crate::song::Track) {
    let _ = writeln!(x, "<Track id=\"{ti}\">");
    cdata(x, "Name", &track.name);
    cdata(x, "ShortName", &track.short_name);
    // A colour per track, as Guitar Pro gives them.
    const COLOURS: [&str; 8] = [
        "235 152 52",
        "52 152 235",
        "76 175 80",
        "156 39 176",
        "244 67 54",
        "0 150 136",
        "255 193 7",
        "96 125 139",
    ];
    let _ = writeln!(x, "<Color>{}</Color>", COLOURS[ti % COLOURS.len()]);
    let (set, program, channel, octave) = match &track.kind {
        Kind::Fretted {
            program, bass_clef, ..
        } => (
            if *bass_clef {
                "<Name>Electric Bass</Name><Type>electricBass</Type>"
            } else {
                "<Name>Electric Guitar</Name><Type>electricGuitar</Type>"
            },
            *program,
            (2 * ti) % 16,
            -1,
        ),
        Kind::Pitched { program, .. } => (
            "<Name>Instrument</Name><Type>other</Type>",
            *program,
            (2 * ti) % 16,
            0,
        ),
        Kind::Drums => ("<Name>Drums</Name><Type>drumKit</Type>", 0, 9, 0),
    };
    let channel = if channel == 9 && !matches!(track.kind, Kind::Drums) {
        10
    } else {
        channel
    };
    let _ = writeln!(
        x,
        "<InstrumentSet>{set}<LineCount>5</LineCount></InstrumentSet>"
    );
    x.push_str("<Staves><Staff><Properties>");
    if let Kind::Fretted { tuning, capo, .. } = &track.kind {
        let pitches: Vec<String> = tuning.iter().map(ToString::to_string).collect();
        let _ = write!(
            x,
            "<Property name=\"CapoFret\"><Fret>{capo}</Fret></Property>\
             <Property name=\"FretCount\"><Number>24</Number></Property>\
             <Property name=\"Tuning\"><Pitches>{}</Pitches></Property>",
            pitches.join(" ")
        );
    }
    if !track.chords.is_empty() {
        x.push_str("<Property name=\"DiagramCollection\"><Items>");
        for (i, d) in track.chords.iter().enumerate() {
            let base = d.base_fret.saturating_sub(1);
            let _ = write!(
                x,
                "<Item id=\"{i}\" name=\"{}\"><Diagram stringCount=\"{}\" fretCount=\"5\" baseFret=\"{}\">",
                d.name,
                d.frets.len(),
                base
            );
            // GPIF counts frets from the diagram's base fret.
            for (s, f) in d.frets.iter().enumerate() {
                if let Some(f) = f {
                    let _ = write!(
                        x,
                        "<Fret string=\"{s}\" fret=\"{}\"/>",
                        f.saturating_sub(base)
                    );
                }
            }
            x.push_str("</Diagram></Item>");
        }
        x.push_str("</Items></Property>");
    }
    x.push_str("</Properties></Staff></Staves>\n");
    let _ = writeln!(
        x,
        "<Transpose><Chromatic>0</Chromatic><Octave>{octave}</Octave></Transpose>"
    );
    let _ = writeln!(
        x,
        "<Sounds><Sound><Name>Sound</Name><MIDI><LSB>0</LSB><MSB>0</MSB><Program>{program}</Program></MIDI></Sound></Sounds>"
    );
    let _ = writeln!(
        x,
        "<MidiConnection><Port>0</Port><PrimaryChannel>{channel}</PrimaryChannel><SecondaryChannel>{channel}</SecondaryChannel></MidiConnection>"
    );
    if !track.lyrics.is_empty() {
        x.push_str("<Lyrics dispatched=\"true\">");
        for (bar, line) in &track.lyrics {
            let _ = write!(
                x,
                "<Line><Text><![CDATA[{line}]]></Text><Offset>{bar}</Offset></Line>"
            );
        }
        x.push_str("</Lyrics>\n");
    }
    x.push_str("<PlaybackState>Default</PlaybackState>\n</Track>\n");
}

/// A MIDI pitch as GPIF writes it.
fn pitch_xml(midi: u8) -> String {
    const STEPS: [(&str, &str); 12] = [
        ("C", ""),
        ("C", "#"),
        ("D", ""),
        ("D", "#"),
        ("E", ""),
        ("F", ""),
        ("F", "#"),
        ("G", ""),
        ("G", "#"),
        ("A", ""),
        ("A", "#"),
        ("B", ""),
    ];
    let (step, accidental) = STEPS[usize::from(midi % 12)];
    format!(
        "<Pitch><Step>{step}</Step><Accidental>{accidental}</Accidental><Octave>{}</Octave></Pitch>",
        i32::from(midi / 12) - 1
    )
}

/// Notes that a later note is tied to: (voice, bar, beat, note).
fn tie_origins(track: &crate::song::Track) -> HashSet<(usize, usize, usize, usize)> {
    let mut out = HashSet::new();
    for (vi, voice) in track.voices.iter().enumerate() {
        let mut last: BTreeMap<u16, (usize, usize, usize)> = BTreeMap::new();
        for (bi, bar) in voice.iter().enumerate() {
            for (ki, beat) in bar.iter().enumerate() {
                for (ni, note) in beat.notes.iter().enumerate() {
                    let key = match note.at {
                        At::Fret(s, _) => u16::from(s),
                        At::Pitch(p) => 256 + u16::from(p),
                    };
                    if note.tied
                        && let Some(&(b, k, n)) = last.get(&key)
                    {
                        out.insert((vi, b, k, n));
                    }
                    last.insert(key, (bi, ki, ni));
                }
            }
        }
    }
    out
}

fn write_beat(
    id: &mut Ids,
    track: &crate::song::Track,
    beat: &Beat,
    is_origin: impl Fn(usize) -> bool,
) -> String {
    let next = id.rhythms.len();
    let rhythm = *id.rhythms.entry(beat.dur).or_insert(next);
    let strings = match &track.kind {
        Kind::Fretted { tuning, .. } => tuning.len(),
        _ => 0,
    };
    let mut note_ids = Vec::new();
    for (ni, note) in beat.notes.iter().enumerate() {
        let nid = id.notes.len();
        note_ids.push(nid.to_string());
        let mut n = format!("<Note id=\"{nid}\">");
        let origin = is_origin(ni);
        if origin || note.tied {
            let _ = write!(
                n,
                "<Tie origin=\"{origin}\" destination=\"{}\"/>",
                note.tied
            );
        }
        let mut accent = 0u32;
        let mut props = String::new();
        let mut harmonic: Option<(&str, f64)> = None;
        for fx in &note.fx {
            match fx {
                Fx::Vibrato => n.push_str("<Vibrato>Slight</Vibrato>"),
                Fx::LetRing => n.push_str("<LetRing/>"),
                Fx::Ghost => n.push_str("<AntiAccent>Normal</AntiAccent>"),
                Fx::Staccato => accent |= 0x01,
                Fx::HeavyAccent => accent |= 0x04,
                Fx::Accent => accent |= 0x08,
                Fx::Trill(f) => {
                    if let (At::Fret(s, _), Kind::Fretted { tuning, capo, .. }) =
                        (note.at, &track.kind)
                    {
                        let open = tuning[strings - usize::from(s)] + capo;
                        let _ = write!(n, "<Trill>{}</Trill>", open + f);
                    }
                }
                Fx::Finger(f) => {
                    let _ = write!(
                        n,
                        "<LeftFingering>{}</LeftFingering>",
                        ["P", "I", "M", "A", "C"][usize::from(*f)]
                    );
                }
                Fx::HammerPull => {
                    props.push_str("<Property name=\"HopoOrigin\"><Enable/></Property>")
                }
                Fx::PalmMute => props.push_str("<Property name=\"PalmMuted\"><Enable/></Property>"),
                Fx::Dead => props.push_str("<Property name=\"Muted\"><Enable/></Property>"),
                Fx::Slide(flags) => {
                    let _ = write!(
                        props,
                        "<Property name=\"Slide\"><Flags>{flags}</Flags></Property>"
                    );
                }
                Fx::Bend | Fx::HalfBend | Fx::BendRelease => {
                    let (middle, end) = match fx {
                        Fx::Bend => (100, 100),
                        Fx::HalfBend => (50, 50),
                        _ => (100, 0),
                    };
                    let _ = write!(
                        props,
                        "<Property name=\"Bended\"><Enable/></Property>\
                         <Property name=\"BendOriginValue\"><Float>0</Float></Property>\
                         <Property name=\"BendOriginOffset\"><Float>0</Float></Property>\
                         <Property name=\"BendMiddleValue\"><Float>{middle}</Float></Property>\
                         <Property name=\"BendMiddleOffset1\"><Float>{}</Float></Property>\
                         <Property name=\"BendMiddleOffset2\"><Float>{}</Float></Property>\
                         <Property name=\"BendDestinationValue\"><Float>{end}</Float></Property>\
                         <Property name=\"BendDestinationOffset\"><Float>100</Float></Property>",
                        if end == 0 { 30 } else { 50 },
                        if end == 0 { 60 } else { 50 },
                    );
                }
                Fx::NaturalHarmonic => harmonic = Some(("Natural", 12.0)),
                Fx::ArtificialHarmonic => harmonic = Some(("Artificial", 12.0)),
                Fx::PinchHarmonic => harmonic = Some(("Pinch", 12.0)),
            }
        }
        if accent != 0 {
            let _ = write!(n, "<Accent>{accent}</Accent>");
        }
        // What Guitar Pro 7 writes for every note besides its place: the
        // pitch three ways. The reader works pitches out itself, but real
        // files are this long, and the speed budget should read as much.
        n.push_str("\n<InstrumentArticulation>0</InstrumentArticulation>\n<Properties>\n");
        let (sounding, written) = match (note.at, &track.kind) {
            (At::Fret(s, f), Kind::Fretted { tuning, capo, .. }) => {
                assert!(
                    usize::from(s) <= strings,
                    "{}: string {s}, but the track has {strings}",
                    track.name
                );
                let open = tuning[strings - usize::from(s)];
                let p = open + capo + f;
                (p, p + 12)
            }
            (At::Fret(..), _) => (60, 60),
            (At::Pitch(p), _) => (p, p),
        };
        let _ = writeln!(
            n,
            "<Property name=\"ConcertPitch\">{}</Property>",
            pitch_xml(sounding)
        );
        match note.at {
            At::Fret(s, f) => {
                // GPIF numbers strings from the lowest.
                let _ = write!(
                    n,
                    "<Property name=\"Fret\">\n<Fret>{f}</Fret>\n</Property>\n\
                     <Property name=\"Midi\">\n<Number>{sounding}</Number>\n</Property>\n\
                     <Property name=\"String\">\n<String>{}</String>\n</Property>\n",
                    strings.saturating_sub(usize::from(s))
                );
            }
            At::Pitch(p) => {
                let _ = writeln!(
                    n,
                    "<Property name=\"Midi\">\n<Number>{p}</Number>\n</Property>"
                );
            }
        }
        let _ = writeln!(
            n,
            "<Property name=\"TransposedPitch\">{}</Property>",
            pitch_xml(written)
        );
        if let Some((kind, fret)) = harmonic {
            let _ = write!(
                n,
                "<Property name=\"HarmonicType\"><HType>{kind}</HType></Property>\
                 <Property name=\"HarmonicFret\"><HFret>{fret}</HFret></Property>"
            );
        }
        if beat.technique == Some("Tapped") {
            n.push_str("<Property name=\"Tapped\"><Enable/></Property>");
        }
        n.push_str(&props);
        n.push_str("</Properties></Note>");
        id.notes.push(n);
    }

    let bid = id.beats.len();
    let mut b = format!(
        "<Beat id=\"{bid}\">\n<Dynamic>{}</Dynamic>\n<Rhythm ref=\"{rhythm}\" />\n\
         <TransposedPitchStemOrientation>Undefined</TransposedPitchStemOrientation>\n\
         <ConcertPitchStemOrientation>Undefined</ConcertPitchStemOrientation>\n",
        beat.dynamic.unwrap_or("MF")
    );
    if !note_ids.is_empty() {
        let _ = write!(b, "<Notes>{}</Notes>", note_ids.join(" "));
    }
    if beat.grace {
        b.push_str("<GraceNotes>BeforeBeat</GraceNotes>");
    }
    if let Some(c) = beat.chord {
        let _ = write!(b, "<Chord>{c}</Chord>");
    }
    if let Some(t) = &beat.text {
        let _ = write!(b, "<FreeText><![CDATA[{t}]]></FreeText>");
    }
    if let Some(t) = beat.tremolo {
        let _ = write!(b, "<Tremolo>{t}</Tremolo>");
    }
    if beat.fade_in {
        b.push_str("<Fadding>FadeIn</Fadding>");
    }
    let mut props = String::new();
    if strings > 0 {
        props.push_str(
            "<Property name=\"PrimaryPickupVolume\">\n<Float>0.500000</Float>\n</Property>\n\
             <Property name=\"PrimaryPickupTone\">\n<Float>0.500000</Float>\n</Property>\n",
        );
    }
    if let Some(dir) = beat.brush {
        let _ = write!(
            props,
            "<Property name=\"Brush\"><Direction>{dir}</Direction></Property>"
        );
    }
    if let Some(t) = beat.technique.filter(|t| *t != "Tapped") {
        let _ = write!(props, "<Property name=\"{t}\"><Enable/></Property>");
    }
    if beat.dive {
        props.push_str(
            "<Property name=\"WhammyBar\"><Enable/></Property>\
             <Property name=\"WhammyBarOriginValue\"><Float>0</Float></Property>\
             <Property name=\"WhammyBarMiddleValue\"><Float>-100</Float></Property>\
             <Property name=\"WhammyBarDestinationValue\"><Float>-200</Float></Property>\
             <Property name=\"WhammyBarOriginOffset\"><Float>0</Float></Property>\
             <Property name=\"WhammyBarMiddleOffset1\"><Float>50</Float></Property>\
             <Property name=\"WhammyBarMiddleOffset2\"><Float>50</Float></Property>\
             <Property name=\"WhammyBarDestinationOffset\"><Float>100</Float></Property>",
        );
    }
    if !props.is_empty() {
        let _ = write!(b, "<Properties>\n{props}</Properties>\n");
    }
    b.push_str("</Beat>");
    id.beats.push(b);
    bid.to_string()
}
